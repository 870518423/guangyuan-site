/* ============================================================
   角色数据 · 空白模板
   ------------------------------------------------------------
   新增一个角色的步骤：
     1. 把这个文件复制成 <id>.js（⚠️ 2026-10-13 M4 定规：**文件名一律 ASCII**，
        即 <id>.js，例如 data/leiou-pifeng.js。中文文件名是历史存量，
        不要再新增——中文路径在服务端/CDN 配置变化时有 404 风险，
        而 SW 预缓存是「全有或全无」，一条 404 会拖垮整次安装）
     2. 改 id / name / meta（id 用英文小写 + 连字符，别用中文，避免 URL 编码问题）
     3. 填 sections
     4. 在 _manifest.js 里加一行 { id, name, file, category, tier }
     5. 加挂载点 <div class="akp" data-akp-char="<id>"></div>

   三个板块的类型（type）固定为 skill / passive / exceed，
   也可以完全不用某个板块 —— 只写你有的那几个。

   改完跑一次数据体检：python tools/akp_lint.py（或直接 pack_deploy.py，第五项自检）
   ============================================================ */
AKP.register({
  /* 必填：唯一 id（英文小写 + 连字符），也是 data-akp-char 的值 */
  id: "character-id",
  /* 必填：显示名 */
  name: "角色名",
  /* 选填：分类信息（多宇宙 / 奥特之星 / 宇宙人 / 怪兽；BY / UL） */
  meta: { category: "多宇宙", tier: "BY" },

  /* ------------------------------------------------------------
     版本定义（选填）
       · 不写、或只有一项 → 该角色不做版本对比，页面不会出现版本按钮
       · 有两项及以上     → 该角色的多版本板块会自动出现底部版本按钮
         状态循环：v1 → v2 → v3 → … → 对比(vN-1 → vN) → 回到 v1
       id       程序用（v1 / v2 / v3）
       badge    标题条右上角的徽标文字
       btnLabel 按钮里怎么称呼它，如 "v2（加强后）"；省略则用 id
     ------------------------------------------------------------ */
  versions: [
    { id: "v1", badge: "v1 原始",   btnLabel: "v1" },
    { id: "v2", badge: "v2 加强后", btnLabel: "v2（加强后）" }
  ],

  /* 选填：模块底部脚注。不写则用统一默认文案 */
  noteText: "……",

  sections: [
    /* ========== 主动技（type: skill）==========
       tag   —— 固定术语，只写「普通技」或「能量技」，**不要改名**
       tone  —— gold（普通技，淡金）/ cyan（能量技，青蓝）
       name  —— 技能名
       text  —— 技能描述；要分段就用 \n */
    {
      type: "skill",
      title: "技能",
      items: [
        { tag: "普通技", tone: "gold", name: "技能名一", text: "描述……" },
        { tag: "能量技", tone: "cyan", name: "技能名二", text: "描述……" }
      ]
    },

    /* ========== 被动（type: passive）==========
       每条：
         no     编号，如 "+1"（页面用绿色显示）
         name   名称（近白加粗）
         text   正文；多条描述用 \n 分隔

       若这一条参与版本对比，把 text 换成 texts：
         texts: { v1: "旧正文", v2: "新正文" }
       并给 diffs 描述改动（对比态用）：
         t     buff=增强(红) / adj=调整(绿) / new=新增(橙) / del=移除(灰删除线)
         to    该改动落在哪个版本（默认最后一项）
         old   旧版本里被改动的原文片段（**必须能在正文里原样找到**）
         new   改动后的值；t='del' 时留空
       isNew: true 表示这条在该角色 v1 里并不存在（只在后续版本新增） */
    {
      type: "passive",
      title: "被动",
      entries: [
        { no: "+1", name: "被动名", text: "描述……" },

        { no: "+6", name: "有改动的被动",
          texts: { v1: "旧正文……", v2: "新正文……" },
          diffs: [
            { t: "buff", old: "旧数值", new: "新数值" },
            { t: "del",  old: "被删掉的一整句。", new: "" },
            { t: "new",  old: "", new: "新增的一整句。" }
          ] }
      ]
    },

    /* ========== 超越技（type: exceed）==========
       badge   右上角徽标（如「进阶+15自动激活」），不需要就不写
       heading 大标题（如「朱雀临世 · 焚尽八荒」）
       paras   段落数组；括号内的效果说明也放这里 */
    {
      type: "exceed",
      title: "超越技能",
      badge: "进阶+15自动激活",
      heading: "大标题",
      paras: ["第一段……", "（第二段……）"]
    }
  ]
});
